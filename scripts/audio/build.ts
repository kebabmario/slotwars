// Renders every Slot Wars sound to WAV, then encodes AAC (.m4a) with macOS `afconvert`.
// Run: npm run audio   (writes public/audio/*.m4a and src/audio/manifest.ts)
import { execFileSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { wav } from './dsp.ts';
import { SFX, renderSfx } from './sfx.ts';
import { AMBIENCE, MUSIC } from './music.ts';

const OUT = 'public/audio';
mkdirSync(OUT, { recursive: true });
const tmp = mkdtempSync(join(tmpdir(), 'slotwars-audio-'));
const manifest: Record<string, { file: string; kind: 'sfx' | 'music' | 'ambience'; loop?: number }> = {};
let total = 0;

function encode(name: string, channels: Float32Array[], bitrate: number) {
  const src = join(tmp, `${name}.wav`), dst = join(OUT, `${name}.m4a`);
  writeFileSync(src, wav(channels));
  execFileSync('afconvert', ['-f', 'm4af', '-d', 'aac', '-b', String(bitrate), src, dst]);
  const kb = statSync(dst).size / 1024;
  total += kb;
  console.log(`${name.padEnd(20)} ${(channels[0].length / 44100).toFixed(2).padStart(6)}s  ${kb.toFixed(1).padStart(7)} KB`);
}

for (const name of Object.keys(SFX)) {
  encode(name, [renderSfx(name)], 64000);
  manifest[name] = { file: `audio/${name}.m4a`, kind: 'sfx' };
}
for (const [name, fn] of Object.entries(MUSIC)) {
  const r = fn();
  encode(`music_${name}`, [r.data.l, r.data.r], 128000);
  manifest[`music_${name}`] = { file: `audio/music_${name}.m4a`, kind: 'music', loop: r.seconds };
}
for (const [name, fn] of Object.entries(AMBIENCE)) {
  const r = fn();
  encode(`amb_${name}`, [r.data.l, r.data.r], 96000);
  manifest[`amb_${name}`] = { file: `audio/amb_${name}.m4a`, kind: 'ambience', loop: r.seconds };
}
rmSync(tmp, { recursive: true, force: true });

mkdirSync('src/audio', { recursive: true });
writeFileSync(
  'src/audio/manifest.ts',
  `// Generated by scripts/audio/build.ts. Do not edit by hand: change the recipes and run \`npm run audio\`.\n` +
    `export type SoundKind = 'sfx' | 'music' | 'ambience';\n` +
    `export interface SoundEntry { file: string; kind: SoundKind; loop?: number }\n` +
    `export const SOUNDS = ${JSON.stringify(manifest, null, 2)} as const satisfies Record<string, SoundEntry>;\n` +
    `export type SoundName = keyof typeof SOUNDS;\n`,
);
console.log(`total ${(total / 1024).toFixed(2)} MB, ${Object.keys(manifest).length} files`);
